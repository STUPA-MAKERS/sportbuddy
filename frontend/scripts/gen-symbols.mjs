// Generates src/app/shared/symbols.generated.ts from @material-symbols/svg-400 (rounded).
// Only the listed glyphs end up in the bundle; no font or request to Google at runtime.
// Run after changing the lists:  npm run symbols
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const root = join(dirname(require.resolve('@material-symbols/svg-400/package.json')), 'rounded');

/** Icons a moderator can give a sport. Keep in sync with nothing else: the UI reads this list. */
export const SPORT_ICONS = [
  'celebration', 'downhill_skiing', 'snowboarding', 'ice_skating', 'sledding', 'badminton',
  'sports_basketball', 'sports_soccer', 'sports_football', 'sports_handball', 'sports_volleyball',
  'sports_tennis', 'sports_baseball', 'sports_cricket', 'sports_golf', 'sports_hockey',
  'sports_rugby', 'sports_martial_arts', 'sports_mma', 'sports_gymnastics', 'sports_esports',
  'directions_run', 'sprint', 'directions_walk', 'nordic_walking', 'hiking', 'landscape',
  'directions_bike', 'pool', 'rowing', 'kayaking', 'sailing', 'surfing', 'kitesurfing',
  'scuba_diving', 'skateboarding', 'roller_skating', 'fitness_center', 'self_improvement',
  'music_note', 'groups', 'sports', 'more_horiz',
];

/** UI glyphs of the mockups that the ui-kit icon set does not have. */
const UI_ICONS = [
  'flag', 'dark_mode', 'light_mode', 'admin_panel_settings', 'block', 'mark_email_read',
  'forward_to_inbox', 'add_circle', 'hourglass_empty', 'visibility', 'visibility_off',
  'done_all', 'drag_indicator', 'calendar_today', 'schedule', 'key', 'warning', 'public',
  'explore', 'add', 'login', 'person',
];

const out = {};
for (const name of [...new Set([...SPORT_ICONS, ...UI_ICONS])]) {
  for (const variant of ['', '-fill']) {
    const svg = readFileSync(join(root, `${name}${variant}.svg`), 'utf8');
    const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
    if (paths.length === 0) throw new Error(`no path in ${name}${variant}`);
    out[`${name}${variant}`] = paths.join(' ');
  }
}

const header = `// Generated by scripts/gen-symbols.mjs from @material-symbols/svg-400 (Apache-2.0). Do not edit.
// viewBox "0 -960 960 960".
`;
writeFileSync(
  new URL('../src/app/shared/symbols.generated.ts', import.meta.url),
  header +
    `export const SPORT_ICONS = ${JSON.stringify(SPORT_ICONS)} as const;\n\n` +
    `export const SYMBOL_PATHS: Record<string, string> = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "')};\n`,
);
console.log(`${Object.keys(out).length} symbols written`);
